//!
//! Czech is the default language. For now a simple table; later it will be
//! replaced by separate translation files so that languages can be added
//! without touching the code.

/// Jazyk rozhraní.
///
/// [en] Interface language.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub enum Lang {
    /// Čeština.
    ///
    /// [en] Czech.
    #[default]
    Cs,
    /// Angličtina.
    ///
    /// [en] English.
    En,
}

impl Lang {
    /// Kód jazyka ISO 639-1 (`"cs"`, `"en"`) – podle něj se vybírají překlady názvů prvků knihoven.
    ///
    /// [en] ISO 639-1 language code (`"cs"`, `"en"`) – used to pick translations of library element names.
    pub fn code(self) -> &'static str {
        match self {
            Self::Cs => "cs",
            Self::En => "en",
        }
    }
}

